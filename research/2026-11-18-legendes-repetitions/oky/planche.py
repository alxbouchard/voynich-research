def decouper(photo, numero):
    (x,y,droite,bas), largeur = ZONES['haut' if numero == 70 else 'rangee']
    echelle = (droite-x)/largeur
    points = [(round(x+a*echelle),round(y+b*echelle)) for a,b in SOMMETS[numero]]
    masque = Image.new('L', photo.size)
    ImageDraw.Draw(masque).polygon(points,fill=255)
    carte = Image.new('RGB',photo.size,'#f0ede8')
    carte.paste(photo,mask=masque)
    return carte.crop(masque.getbbox())

def main(source):
    donnees = source.read_bytes()
    if hashlib.sha256(donnees).hexdigest() != SHA256:
        raise ValueError('Empreinte de la photographie source différente')
    police = ImageFont.load_default(size=27)
    planche = Image.new('RGB',(1250,1010),'#f0ede8')
    dessin = ImageDraw.Draw(planche)
    with Image.open(source) as photo:
        # Gros plans documentaires réservés à la vérification après classement.
        photo.crop((580,120,1200,590)).save(OUT/'attache-70.jpg',quality=92)
        photo.crop((1280,1050,1890,1290)).save(OUT/'attache-84.jpg',quality=92)
        for i, numero in enumerate([70] + ORDRE):
            if i == 0:
                pos_x,pos_y = 625,0
                nom = 'X'
            else:
                col = (i-1)%4
                rang = (i-1)//4
                pos_x,pos_y = 155+310*col,340+330*rang
                nom = chr(64+i)
            extrait=decouper(photo,numero)
            facteur=min(292/extrait.width,267/extrait.height)
            extrait=extrait.resize((round(extrait.width*facteur),round(extrait.height*facteur)),Image.Resampling.LANCZOS)
            dessin.text((pos_x,pos_y+10),nom,font=police,anchor='mt',fill='#222222')
            planche.paste(extrait,(pos_x-extrait.width//2,pos_y+50+(270-extrait.height)//2))
    planche.save(OUT/'planche.jpg',quality=92,subsampling=0)

