def native(point):
    x, y = point
    return (round(205+(x-30)*2695/1440), round(310+(y-111)*2695/1440))


def masked(im, border, hole=()):
    mask = Image.new("L", im.size)
    draw = ImageDraw.Draw(mask)
    draw.polygon(border, fill=255)
    if hole:
        draw.polygon(hole, fill=0)
    r = mask.getbbox()
    return Image.composite(im.crop(r), Image.new("RGB",(r[2]-r[0],r[3]-r[1]),"white"), mask.crop(r))


def panel(pic, code, size):
    w,h = size
    c = Image.new("RGB",size,"white")
    draw = ImageDraw.Draw(c)
    try:
        face = ImageFont.truetype("DejaVuSans.ttf",24)
    except OSError:
        face = ImageFont.truetype("Arial.ttf",24)
    draw.text((10,0),code,fill="#17252c",font=face)
    pic = pic.copy()
    pic.thumbnail((w-20,h-37),Image.Resampling.LANCZOS)
    c.paste(pic,((w-pic.width)//2,31+(h-34-pic.height)//2))
    return c


def main():
    p = argparse.ArgumentParser()
    p.add_argument("f89",type=Path)
    p.add_argument("f100",type=Path)
    p.add_argument("f102",type=Path)
    args = p.parse_args()
    earlier=json.loads(PREVIOUS.read_text())
    models={}
    for frag,key,path in [(36,"89",args.f89),(140,"100",args.f100)]:
        source=earlier["sources"][key]
        assert sha256(path.read_bytes()).hexdigest()==source["sha256"]
        data=earlier["fragments"][str(frag)]
        models[frag]=masked(Image.open(path).convert("RGB"),[tuple(v) for v in data["polygone_natif"]],
                            [tuple(v) for v in data["exclusion_native"]])
    assert sha256(args.f102.read_bytes()).hexdigest()==DIGEST
    with Image.open(args.f102) as img:
        drawings={n:masked(img,[native(v) for v in border]) for n,border in OUTLINES.items()}
        img.crop((825,785,1200,1124)).save(HERE/"detail-222.png",optimize=True)
        img.crop((1480,523,1990,1147)).save(HERE/"detail-224.png",optimize=True)
    key={}
    for name, model, seed in [("ambre",36,22122736),("indigo",140,221227140)]:
        order=list(range(221,228))
        random.Random(seed).shuffle(order)
        key[name]={"modele":model,"graine":seed,"codes":dict(zip("ABCDEFG",order))}
        board=Image.new("RGB",(1340,930),"white")
        board.paste(panel(models[model],"Modèle",(460,330)),(435,0))
